import fs from "node:fs";

const source = process.argv[2] ?? "https://encoding.spec.whatwg.org/";
const load = async (name) =>
  JSON.parse(
    source.startsWith("https://")
      ? await (await fetch(new URL(name, source))).text()
      : fs.readFileSync(`${source}/${name}`, "utf8"),
  );
const [groups, indexes] = await Promise.all([
  load("encodings.json"),
  load("indexes.json"),
]);

const alphabet = Array.from({ length: 0x7f - 0x21 }, (_, offset) =>
  String.fromCharCode(0x21 + offset),
).filter((character) => character !== '"' && character !== "\\");
const half = 45;
const nulls = alphabet[90];
const run = alphabet[91];

const number = (value) => {
  let out = "";
  while (value >= half) {
    out += alphabet[half + (value % half)];
    value = Math.floor(value / half);
  }
  return out + alphabet[value];
};

const pack = (values) => {
  let out = "";
  let last = 0;
  for (let position = 0; position < values.length;) {
    let length = 0;
    while (
      values[position + length] == null &&
      position + length < values.length
    ) {
      length++;
    }
    if (length > 0) {
      out += nulls + number(length - 1);
      position += length;
      continue;
    }
    while (values[position + length] === last + length + 1) {
      length++;
    }
    if (length > 1) {
      out += run + number(length - 1);
      last += length;
      position += length;
      continue;
    }
    const delta = values[position] - last;
    out += number(delta < 0 ? -2 * delta - 1 : 2 * delta);
    last = values[position++];
  }
  return out;
};

const literal = (text) => {
  const lines = text.match(/.{1,160}/g) ?? [""];
  return lines.map((line) => JSON.stringify(line)).join(" +\n    ");
};

const table = (values) =>
  `{ length: ${values.length}, data: ${literal(pack(values))} }`;

const names = groups.flatMap((group) =>
  group.encodings.map((encoding) => encoding.name.toLowerCase()),
);
const labels = groups.flatMap((group) =>
  group.encodings.map(
    (encoding) =>
      `  ${JSON.stringify(encoding.name.toLowerCase())}: ${JSON.stringify(encoding.labels)},`,
  ),
);
const singleByte = groups
  .find((group) => group.heading === "Legacy single-byte encodings")
  .encodings.map((encoding) => {
    const name = encoding.name.toLowerCase();
    return `  ${JSON.stringify(name)}: ${table(indexes[name === "iso-8859-8-i" ? "iso-8859-8" : name])},`;
  });
const multiByte = ["big5", "euc-kr", "gb18030", "jis0208", "jis0212"].map(
  (name) => `  ${JSON.stringify(name)}: ${table(indexes[name])},`,
);
const ranges = indexes["gb18030-ranges"];

const header =
  "// Generated by encodings.mjs from the WHATWG Encoding Standard.\n";

const encodings = `${header}
export type Encoding = ${names.map((name) => JSON.stringify(name)).join(" | ")};

export const labels: Readonly<Record<Encoding, readonly string[]>> = {
${labels.join("\n")}
};
`;

const tables = `${header}
export interface Table {
  readonly length: number;
  readonly data: string;
}

export const singleByte: Readonly<Record<string, Table>> = {
${singleByte.join("\n")}
};

export const multiByte: Readonly<Record<"big5" | "euc-kr" | "gb18030" | "jis0208" | "jis0212", Table>> = {
${multiByte.join("\n")}
};

export const gb18030Ranges = {
  pointers: ${table(ranges.map(([pointer]) => pointer))},
  codePoints: ${table(ranges.map(([, codePoint]) => codePoint))},
};
`;

fs.writeFileSync(
  new URL("src/shared/encodings.ts", import.meta.url),
  encodings,
);
fs.writeFileSync(
  new URL("src/shared/encoding-tables.ts", import.meta.url),
  tables,
);
